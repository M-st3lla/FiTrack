-- FiTrack database schema (PostgreSQL).
-- Running this file (via `flask --app app init-db`) drops and recreates every table.

DROP TABLE IF EXISTS contact_messages CASCADE;
DROP TABLE IF EXISTS sessions CASCADE;
DROP TABLE IF EXISTS goals CASCADE;
DROP TABLE IF EXISTS user_workouts CASCADE;
DROP TABLE IF EXISTS nutrition_tips CASCADE;
DROP TABLE IF EXISTS exercises CASCADE;
DROP TABLE IF EXISTS workout_categories CASCADE;
DROP TABLE IF EXISTS profiles CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- Accounts ------------------------------------------------------------------
CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Key body information the user enters: age, weight, height, calories to burn
CREATE TABLE profiles (
    user_id          INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    age              INTEGER,
    weight_kg        DOUBLE PRECISION,
    height_cm        DOUBLE PRECISION,
    calories_to_burn INTEGER,
    fitness_level    TEXT CHECK (fitness_level IN ('beginner', 'intermediate', 'advanced')),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Workout catalogue ---------------------------------------------------------
CREATE TABLE workout_categories (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE exercises (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  INTEGER NOT NULL REFERENCES workout_categories(id) ON DELETE CASCADE,
    name         TEXT NOT NULL,
    description  TEXT,
    sets         INTEGER,
    reps         INTEGER,
    duration_min INTEGER
);

CREATE TABLE nutrition_tips (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES workout_categories(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    foods       TEXT NOT NULL,
    description TEXT NOT NULL
);

-- Workouts a user has selected
CREATE TABLE user_workouts (
    user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES workout_categories(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, category_id)
);

-- Goals with a deadline
CREATE TABLE goals (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id      INTEGER NOT NULL REFERENCES workout_categories(id),
    title            TEXT NOT NULL,
    target_calories  INTEGER,
    target_weight_kg DOUBLE PRECISION,
    start_date       DATE NOT NULL,
    end_date         DATE NOT NULL,
    status           TEXT NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'completed', 'abandoned')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Scheduled gym sessions
CREATE TABLE sessions (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id  INTEGER NOT NULL REFERENCES workout_categories(id),
    goal_id      INTEGER REFERENCES goals(id) ON DELETE SET NULL,
    session_date DATE NOT NULL,
    start_time   TIME NOT NULL,
    duration_min INTEGER NOT NULL DEFAULT 60,
    notes        TEXT,
    status       TEXT NOT NULL DEFAULT 'scheduled'
                 CHECK (status IN ('scheduled', 'completed', 'cancelled')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_sessions_user_date ON sessions(user_id, session_date);

-- Contact form
CREATE TABLE contact_messages (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    email      TEXT NOT NULL,
    subject    TEXT,
    message    TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
